const DICTS: Record<Lang, Dict> = { de, en, ru }

export function getLang(): Lang {
  const saved = localStorage.getItem('lang') as Lang | null
  // Englisch ist die Hauptsprache — Deutsch war nur der Entwicklungsstand.
  return saved && DICTS[saved] ? saved : 'en'
}

/** Hat der Benutzer schon einmal eine Sprache gewählt? */
export function langChosen(): boolean {
  const saved = localStorage.getItem('lang')
  return !!saved && saved in DICTS
}

export function setLang(lang: Lang): void {
  localStorage.setItem('lang', lang)
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.de[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export const LangContext = createContext<Lang>('de')

/** Aktuelle Sprache — z. B. um sie an den Hauptprozess zu reichen. */
export function useLang(): Lang {
  return useContext(LangContext)
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useContext(LangContext)
  return (key, vars) => translate(lang, key, vars)
}
